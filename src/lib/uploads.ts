import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { inflateSync } from "node:zlib";
import path from "node:path";
import type { AttachmentKind, Prisma } from "@/generated/prisma/client";
import { prisma } from "./prisma";
import { UserError } from "./action";

// Uploads live outside the build output; skip bundler tracing of this path.
const UPLOAD_DIR = path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR ?? path.join(process.cwd(), "uploads"));
const MAX_BYTES = 10 * 1024 * 1024;
const ALLOWED = /^(image\/(jpeg|png|webp|gif|heic|heif)|application\/pdf)$/;

type Owner = Omit<Prisma.AttachmentUncheckedCreateInput, "kind" | "storageKey" | "fileName" | "mimeType" | "sizeBytes" | "uploadedById" | "uploadedByAccountId">;

/** Max files per portal upload, so one form can't fill the disk. */
export const MAX_FILES_PER_UPLOAD = 10;

/**
 * Save uploaded files to disk and create Attachment rows linked to `owner`.
 * `uploader` is a staff user id, or `{ accountId }` for a customer in the portal.
 */
export async function saveAttachments(files: File[], kind: AttachmentKind, uploader: string | { accountId: string }, owner: Owner) {
  if (typeof uploader !== "string" && files.length > MAX_FILES_PER_UPLOAD) throw new UserError(`Upload at most ${MAX_FILES_PER_UPLOAD} files at a time`);
  const by = typeof uploader === "string" ? { uploadedById: uploader } : { uploadedByAccountId: uploader.accountId };
  for (const f of files) {
    if (f.size > MAX_BYTES) throw new UserError(`${f.name} is larger than 10 MB`);
    if (!ALLOWED.test(f.type)) throw new UserError(`${f.name}: only images and PDF files are allowed`);
  }
  await mkdir(UPLOAD_DIR, { recursive: true });
  for (const f of files) {
    const ext = path.extname(f.name).toLowerCase().replace(/[^.a-z0-9]/g, "");
    const storageKey = `${randomUUID()}${ext}`;
    await writeFile(path.join(UPLOAD_DIR, storageKey), Buffer.from(await f.arrayBuffer()));
    await prisma.attachment.create({
      data: { ...owner, kind, storageKey, fileName: f.name, mimeType: f.type, sizeBytes: f.size, ...by },
    });
  }
}

export async function readAttachment(storageKey: string): Promise<Buffer> {
  // storageKey is generated by us, but guard against path tricks anyway.
  const file = path.join(UPLOAD_DIR, path.basename(storageKey));
  return readFile(file);
}

/** Product-line files: images are stored as product images, PDFs as other files. */
export async function saveLineFiles(files: File[], uploader: string | { accountId: string }, owner: Owner) {
  const images = files.filter((f) => f.type.startsWith("image/"));
  const others = files.filter((f) => !f.type.startsWith("image/"));
  if (images.length) await saveAttachments(images, "PRODUCT_IMAGE", uploader, owner);
  if (others.length) await saveAttachments(others, "OTHER", uploader, owner);
}

export const LOGO_MAX_BYTES = 2 * 1024 * 1024;
export type StoredLogo = { key: string; mime: "image/png" | "image/jpeg" | "image/svg+xml"; fileName: string };

/**
 * Organization logo: PNG, JPG or SVG up to 2 MB, checked by the file's actual
 * content (not its name). SVGs with scripts or event handlers are refused; the
 * logo route also serves SVG with a sandboxing Content-Security-Policy.
 */
export async function saveLogo(f: File, opts: { allowSvg?: boolean } = {}): Promise<StoredLogo> {
  if (f.size === 0) throw new UserError("Choose a logo file");
  if (f.size > LOGO_MAX_BYTES) throw new UserError("The logo must be 2 MB or smaller");
  const buf = Buffer.from(await f.arrayBuffer());
  let mime: StoredLogo["mime"];
  let ext: string;
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) {
    if (!pngDecodes(buf)) throw new UserError("This PNG file is damaged – export it again and re-upload");
    [mime, ext] = ["image/png", ".png"];
  }
  else if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) [mime, ext] = ["image/jpeg", ".jpg"];
  else {
    const text = buf.toString("utf8");
    if (!/^\s*(<\?xml[^>]*>\s*)?(<!--[\s\S]*?-->\s*)*(<!DOCTYPE[^>]*>\s*)?<svg[\s>]/i.test(text)) throw new UserError(opts.allowSvg === false ? "The logo must be a PNG or JPG image" : "The logo must be a PNG, JPG or SVG image");
    if (opts.allowSvg === false) throw new UserError("The logo must be a PNG or JPG image (SVG can't be used on PDFs)");
    if (/<script|javascript:|\son[a-z]+\s*=|<foreignObject/i.test(text)) throw new UserError("This SVG contains scripts and can't be used as a logo");
    [mime, ext] = ["image/svg+xml", ".svg"];
  }
  await mkdir(UPLOAD_DIR, { recursive: true });
  const key = `logo-${randomUUID()}${ext}`;
  await writeFile(path.join(UPLOAD_DIR, key), buf);
  return { key, mime, fileName: f.name };
}

/** True when the PNG's image data actually decompresses (a damaged PNG would break PDF rendering). */
function pngDecodes(buf: Buffer) {
  try {
    const parts: Buffer[] = [];
    for (let i = 8; i + 8 <= buf.length; ) {
      const len = buf.readUInt32BE(i);
      const type = buf.toString("latin1", i + 4, i + 8);
      if (type === "IDAT") parts.push(buf.subarray(i + 8, i + 8 + len));
      if (type === "IEND") break;
      i += 12 + len;
    }
    return parts.length > 0 && inflateSync(Buffer.concat(parts)).length > 0;
  } catch {
    return false;
  }
}

/** Store a generated PDF; returns its storage key (read back with readAttachment). */
export async function saveGeneratedPdf(pdf: Buffer, prefix: string): Promise<string> {
  await mkdir(UPLOAD_DIR, { recursive: true });
  const key = `doc-${prefix.replace(/[^a-z0-9-]/gi, "")}-${randomUUID()}.pdf`;
  await writeFile(path.join(UPLOAD_DIR, key), pdf);
  return key;
}
