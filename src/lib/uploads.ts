import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { AttachmentKind, Prisma } from "@/generated/prisma/client";
import { prisma } from "./prisma";
import { UserError } from "./action";

// Uploads live outside the build output; skip bundler tracing of this path.
const UPLOAD_DIR = path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR ?? path.join(process.cwd(), "uploads"));
const MAX_BYTES = 10 * 1024 * 1024;
const ALLOWED = /^(image\/(jpeg|png|webp|gif|heic|heif)|application\/pdf)$/;

type Owner = Omit<Prisma.AttachmentUncheckedCreateInput, "kind" | "storageKey" | "fileName" | "mimeType" | "sizeBytes" | "uploadedById" | "uploadedByAccountId">;

/** Max files per portal upload, so one form can't fill the disk. */
export const MAX_FILES_PER_UPLOAD = 10;

/**
 * Save uploaded files to disk and create Attachment rows linked to `owner`.
 * `uploader` is a staff user id, or `{ accountId }` for a customer in the portal.
 */
export async function saveAttachments(files: File[], kind: AttachmentKind, uploader: string | { accountId: string }, owner: Owner) {
  if (typeof uploader !== "string" && files.length > MAX_FILES_PER_UPLOAD) throw new UserError(`Upload at most ${MAX_FILES_PER_UPLOAD} files at a time`);
  const by = typeof uploader === "string" ? { uploadedById: uploader } : { uploadedByAccountId: uploader.accountId };
  for (const f of files) {
    if (f.size > MAX_BYTES) throw new UserError(`${f.name} is larger than 10 MB`);
    if (!ALLOWED.test(f.type)) throw new UserError(`${f.name}: only images and PDF files are allowed`);
  }
  await mkdir(UPLOAD_DIR, { recursive: true });
  for (const f of files) {
    const ext = path.extname(f.name).toLowerCase().replace(/[^.a-z0-9]/g, "");
    const storageKey = `${randomUUID()}${ext}`;
    await writeFile(path.join(UPLOAD_DIR, storageKey), Buffer.from(await f.arrayBuffer()));
    await prisma.attachment.create({
      data: { ...owner, kind, storageKey, fileName: f.name, mimeType: f.type, sizeBytes: f.size, ...by },
    });
  }
}

export async function readAttachment(storageKey: string): Promise<Buffer> {
  // storageKey is generated by us, but guard against path tricks anyway.
  const file = path.join(UPLOAD_DIR, path.basename(storageKey));
  return readFile(file);
}

/** Product-line files: images are stored as product images, PDFs as other files. */
export async function saveLineFiles(files: File[], uploader: string | { accountId: string }, owner: Owner) {
  const images = files.filter((f) => f.type.startsWith("image/"));
  const others = files.filter((f) => !f.type.startsWith("image/"));
  if (images.length) await saveAttachments(images, "PRODUCT_IMAGE", uploader, owner);
  if (others.length) await saveAttachments(others, "OTHER", uploader, owner);
}
