export function translateError(lang: Lang, msg: string | undefined): string | undefined {
  if (!msg || lang === "en") return msg;
  for (const [re, bnText] of ERRORS_BN) {
    const m = msg.match(re);
    if (m) return bnText.replace(/\$(\d)/g, (_, n) => m[Number(n)] ?? "").replace(" (কারণ: )", "");
  }
  return msg;
}
